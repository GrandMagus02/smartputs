/**
 * Regenerates every `packages/<kind>/corpus/uk.tsv`.
 *
 * ```sh
 * bun run packages/kinds/.scratch/gen-uk.ts
 * ```
 *
 * It lives here, in the one package that already depends on all the others, so
 * that a single file can build each package's corpus engine *exactly* as that
 * package's own `corpus.test.ts` builds it — same kinds, same vocabularies,
 * nothing else. If the two ever drift, the corpus stops describing the package.
 *
 * The inputs and the `#` lines between them are written by hand: choosing the
 * rows is the whole work, and they are the claim the file makes. The three
 * answer columns are read back off the engine, because a formatted Ukrainian
 * string carries U+00A0 grouping and a decimal comma that are invisible in a
 * diff and unretypeable by hand. What makes the result a test rather than a
 * recording is that every generated row was read and approved before it landed
 * — the same rule `packages/core/corpus/uk.tsv` was written under, which is how
 * that file arrived carrying two rows marked KNOWN WRONG instead of blessed.
 */
