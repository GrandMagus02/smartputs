for (const { pkg, engine, lines } of CORPORA) {
  const out: string[] = [];
  for (const line of lines) {
    if (line.startsWith("#")) {
      out.push(line);
      continue;
    }
    const r = engine.evaluate(line);
    out.push([line, r.kind, r.value.canonical.toString(), r.formatted].join("\t"));
  }
  const url = new URL(`../../${pkg}/corpus/uk.tsv`, import.meta.url);
  await Bun.write(url, `${out.join("\n")}\n`);
  console.log(`${pkg}: ${out.filter((l) => !l.startsWith("#")).length} rows`);
}
